"""Campaign lane launcher for the LSB ops console.

SubprocessLaneLauncher spawns one detached process per model, each running
collect.py for the model's shortfall cells sequentially. All output goes to
a per-model log file. Pidfiles are written atomically via a .tmp + rename.

The LaneLauncher protocol is defined here so callers (routes, tests) can
depend on the abstraction without importing subprocess directly.

lane.sh is written as an auditable reference mirroring
logs/collect-batchA-20260710/resume.sh; it is not executed by this module
but can be run manually by the operator to reproduce or resume a campaign.

No LLM imports. Read-only over data/raw/informants.jsonl. Rule 14 compliant.
"""

from __future__ import annotations

import json
import os
import subprocess
from pathlib import Path
from typing import Any, Protocol

from .planner import CampaignPlan, CellShortfall, render_plan_text

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _safe_model(model_id: str) -> str:
    """Convert a model_id to a filesystem-safe name (/ -> _)."""
    return model_id.replace("/", "_")


def _build_lane_argv(
    model_id: str,
    domain_slug: str,
    needed: int,
    campaign_id: str,
    repo_root: Path,
) -> list[str]:
    """Build the argv list for one collect.py invocation.

    Returns:
        list of string tokens: uv run python scripts/collect.py ...
    """
    return [
        "uv",
        "run",
        "python",
        str(repo_root / "scripts" / "collect.py"),
        "--domain",
        domain_slug,
        "--mode",
        "single_pass",
        "--model",
        model_id,
        "--runs",
        str(needed),
        "--campaign-id",
        campaign_id,
    ]


