# ---------------------------------------------------------------------------
# Shell-script renderer (audit reference, not executed by launcher)
# ---------------------------------------------------------------------------


def _render_lane_sh(plan: CampaignPlan, log_root: Path, repo_root: Path) -> str:
    """Render a lane.sh that mirrors logs/collect-batchA-20260710/resume.sh.

    The script is written as an auditable reference. Operators can run it
    manually to reproduce or resume a campaign. The launcher itself does not
    execute this file; it spawns lanes directly via subprocess.Popen.

    Layout mirrors resume.sh exactly:
    - set -uo pipefail
    - cd to repo root
    - LOGDIR / CID / PLAN variables
    - mapfile to collect unique models from plan.txt
    - per-model subshell loop over plan.txt; sequential collect.py calls
    - wait loop with fail sentinel
    """
    logdir = str(log_root)
    cid = plan.campaign_id or "ops-console-campaign"
    plan_txt_rel = str(log_root / "plan.txt")

    lines = [
        "#!/usr/bin/env bash",
        "# Generated by SubprocessLaneLauncher. Mirrors resume.sh layout.",
        "# Run manually to reproduce or resume a campaign.",
        "set -uo pipefail",
        f"cd {repo_root}",
        f"LOGDIR={logdir}",
        f"CID={cid}",
        f'PLAN="{plan_txt_rel}"',
        "",
        "mapfile -t MODELS < <(awk '{print $1}' \"$PLAN\" | sort -u)",
        "",
        "pids=()",
        "for M in \"${MODELS[@]}\"; do",
        '  SAFE=${M//\\//_}',
        "  (",
        "    while read -r m d need; do",
        '      [ "$m" = "$M" ] || continue',
        '      echo "=== $(date -u +%FT%TZ) LANE $M / $d runs=$need ===" >> "$LOGDIR/$SAFE.log"',
        "      uv run python scripts/collect.py --domain \"$d\" --mode single_pass \\",
        "        --model \"$M\" --runs \"$need\" --campaign-id \"$CID\" \\",
        '        >> "$LOGDIR/$SAFE.log" 2>&1',
        '      echo "=== exit $? ===" >> "$LOGDIR/$SAFE.log"',
        "    done < \"$PLAN\"",
        "  ) &",
        "  pids+=($!)",
        "done",
        "",
        "fail=0",
        "for p in \"${pids[@]}\"; do wait \"$p\" || fail=1; done",
        'echo "lanes done fail=$fail"',
    ]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Subprocess lane launcher
# ---------------------------------------------------------------------------


class SubprocessLaneLauncher:
    """Launches one detached subprocess per model in the campaign plan.

    Each subprocess runs collect.py for all of that model's shortfall cells
    sequentially (domains in plan order). Stdout and stderr are appended to
    {log_root}/{safe_model}.log. The process group is detached from the
    console via start_new_session=True so that console restarts do not kill
    running lanes.

    Pidfiles are written atomically: written to {safe_model}.pid.tmp then
    renamed to {safe_model}.pid, so readers never see a partial write.

    The _spawn callable is injectable for testing. Its signature matches
    subprocess.Popen: _spawn(argv, stdout, stderr, start_new_session, cwd, env)
    and it must return an object with a .pid attribute.
    """

    def __init__(self, _spawn: Any = None) -> None:
        self._spawn: Any = _spawn if _spawn is not None else subprocess.Popen

    def launch(
        self,
        plan: CampaignPlan,
        log_root: Path,
        repo_root: Path,
    ) -> dict[str, int]:
        """Launch all lanes and return model_id -> PID mapping.

        Writes to log_root:
        - plan.json: machine-readable shortfall snapshot
        - plan.txt:  human-readable plan (mirrors resume-plan.txt layout)
        - lane.sh:   auditable shell script reference (mirrors resume.sh)
        - {safe_model}.log: per-lane stdout+stderr (opened in append mode)
        - {safe_model}.pid: per-lane PID (written atomically)
        """
        log_root.mkdir(parents=True, exist_ok=True)

        # Write plan.json
        cells_with_work = [c for c in plan.cells if c.needed > 0]
        plan_data: dict[str, Any] = {
            "campaign_id": plan.campaign_id,
            "runs_per_cell": plan.runs_per_cell,
            "cells": [
                {
                    "model_id": c.model_id,
                    "domain_slug": c.domain_slug,
                    "passed": c.passed,
                    "needed": c.needed,
                }
                for c in cells_with_work
            ],
        }
        (log_root / "plan.json").write_text(
            json.dumps(plan_data, indent=2, ensure_ascii=False), encoding="utf-8"
        )

        # Write plan.txt (mirrors resume-plan.txt; lane.sh reads it)
        plan_txt = render_plan_text(plan)
        (log_root / "plan.txt").write_text(plan_txt, encoding="utf-8")

        # Write lane.sh (auditable reference, not executed by this launcher)
        lane_sh_content = _render_lane_sh(plan, log_root, repo_root)
        lane_sh_path = log_root / "lane.sh"
        lane_sh_path.write_text(lane_sh_content, encoding="utf-8")
        lane_sh_path.chmod(0o755)

        # Collect models that have at least one cell needing work
        models_ordered: list[str] = []
        seen_models: set[str] = set()
        for cell in cells_with_work:
            if cell.model_id not in seen_models:
                models_ordered.append(cell.model_id)
                seen_models.add(cell.model_id)

        pids: dict[str, int] = {}

        for model_id in models_ordered:
            safe = _safe_model(model_id)
            log_path = log_root / f"{safe}.log"

            # Build a bash inline script that runs collect.py for each domain
            # of this model sequentially. This exactly mirrors the subshell in
            # resume.sh but scoped to one model.
            model_cells = [c for c in cells_with_work if c.model_id == model_id]
            bash_lines = self._build_lane_bash(model_id, model_cells, plan.campaign_id, repo_root)

            argv = ["bash", "-c", bash_lines]
            env = dict(os.environ)

            with open(log_path, "ab") as log_fh:
                proc = self._spawn(
                    argv,
                    stdout=log_fh,
                    stderr=log_fh,
                    start_new_session=True,
                    cwd=str(repo_root),
                    env=env,
                )

            pid: int = proc.pid
            _write_pidfile_atomic(log_root / f"{safe}.pid", pid)
            pids[model_id] = pid

        return pids

    @staticmethod
    def _build_lane_bash(
        model_id: str,
        cells: list[CellShortfall],
        campaign_id: str,
        repo_root: Path,
    ) -> str:
        """Build a bash inline script that runs collect.py for each domain."""
        collect_script = str(repo_root / "scripts" / "collect.py")
        collect_invocations = []
        for cell in cells:
            collect_invocations.append(
                f"uv run python {collect_script}"
                f" --domain {cell.domain_slug}"
                f" --mode single_pass"
                f" --model {model_id}"
                f" --runs {cell.needed}"
                f" --campaign-id {campaign_id}"
            )
        return "\n".join(collect_invocations)


# ---------------------------------------------------------------------------
# Pidfile helpers
# ---------------------------------------------------------------------------


def _write_pidfile_atomic(pidfile_path: Path, pid: int) -> None:
    """Write a PID to a pidfile atomically using a .tmp intermediate.

    Writes to {pidfile_path}.tmp then renames to pidfile_path. This
    ensures readers never see a partial write.
    """
    tmp_path = pidfile_path.with_suffix(".pid.tmp")
    tmp_path.write_text(str(pid), encoding="utf-8")
    tmp_path.rename(pidfile_path)
